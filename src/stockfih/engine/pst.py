TABLES = {
    chess.PAWN: PAWN,
    chess.KNIGHT: KNIGHT,
    chess.BISHOP: BISHOP,
    chess.ROOK: ROOK,
    chess.QUEEN: QUEEN,
}


def positional(board: chess.Board) -> int:
    # White minus Black, in centipawns, from piece placement only.
    # shortcut: endgame = no queens on the board (picks the king table). A smooth blend
    # between the two king tables is better; upgrade when tuning in Phase 14.
    endgame = not board.queens
    total = 0
    for square, piece in board.piece_map().items():
        if piece.piece_type == chess.KING:
            table = KING_ENDGAME if endgame else KING_MIDDLEGAME
        else:
            table = TABLES[piece.piece_type]
        # Tables start at a8 (index 0); python-chess squares start at a1 (0).
        # White: flip the rank (square ^ 56). Black sees the mirror image, so it uses the square as is.
        if piece.color == chess.WHITE:
            total += table[square ^ 56]
        else:
            total -= table[square]
    return total
